    si.product_id,
    s.warehouse_id,
    'OUT',
    si.quantity,
    'SALE',
    s.sale_id
FROM sales s
INNER JOIN sale_items si
    ON s.sale_id = si.sale_id
WHERE s.sale_status = 'Completed'
  AND s.sale_id BETWEEN 11 AND 100
ORDER BY s.sale_id
LIMIT 43;

