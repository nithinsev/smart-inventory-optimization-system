INSERT INTO stock_movements
(product_id, warehouse_id, movement_type, quantity, reference_type, reference_id)
SELECT
    pi.product_id,
    pu.warehouse_id,
    'IN',
    pi.quantity,
    'PURCHASE',
    pu.purchase_id
FROM purchases pu
INNER JOIN purchase_items pi
    ON pu.purchase_id = pi.purchase_id
WHERE pu.purchase_status = 'Received'
  AND pu.purchase_id BETWEEN 11 AND 100
ORDER BY pu.purchase_id
LIMIT 43;

